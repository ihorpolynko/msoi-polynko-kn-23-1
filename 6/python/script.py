# =====================================================
# 1. НАЗВИ ТЕРМІВ
# =====================================================

terms = ["LOW", "MEDIUM", "HIGH"]

# =====================================================
# 2. ПАРАМЕТРИ ФУНКЦІЙ ПРИНАЛЕЖНОСТІ
# =====================================================

# ---------------- A ----------------
a_A = [10, 20, 30]
b_A = [0.5, 0.4, 0.5]

# ---------------- B ----------------
c_B = [160, None, None]
b_B = [175, 210, None]
a_B = [None, 154, 200]

c2 = 190
c3 = 215

# ---------------- C ----------------
a_C = [0.1, 75, 0.09]
b_C = [1, 134, 1.5]
c_C = [40, 90, 150]
d_C = [None, 110, None]

# =====================================================
# 3. ФУНКЦІЇ ПРИНАЛЕЖНОСТІ
# =====================================================

# ---------------- A ----------------

def mu_A1(x):
    if x < a_A[0]:
        return 1
    else:
        return np.exp(-abs((x - a_A[0]) / (2 * b_A[0])))

def mu_A2(x):
    return np.exp(-abs((x - a_A[1]) / (2 * b_A[1])))

def mu_A3(x):
    if x > a_A[2]:
        return 1
    else:
        return np.exp(-abs((x - a_A[2]) / (2 * b_A[2])))

# ---------------- B ----------------

def mu_B1(x):
    if x < c_B[0]:
        return 1
    elif c_B[0] < x < b_B[0]:
        return (b_B[0] - x) / (b_B[0] - c_B[0])
    else:
        return 0

def mu_B2(x):
    if x <= a_B[1]:
        return 0
    elif a_B[1] < x < c2:
        return (x - a_B[1]) / (c2 - a_B[1])
    elif c2 <= x < b_B[1]:
        return 1
    else:
        return 0

def mu_B3(x):
    if x <= a_B[2]:
        return 0
    elif a_B[2] < x < c3:
        return (x - a_B[2]) / (c3 - a_B[2])
    else:
        return 1

# ---------------- C ----------------

def mu_C1(x):
    if x < c_C[0]:
        return 1
    else:
        return 1 / (1 + (a_C[0] * (x - c_C[0])) ** b_C[0])

def mu_C2(x):
    if x <= a_C[1]:
        return 0
    elif a_C[1] < x < c_C[1]:
        return (x - a_C[1]) / (c_C[1] - a_C[1])
    elif c_C[1] <= x <= d_C[1]:
        return 1
    elif d_C[1] < x < b_C[1]:
        return (b_C[1] - x) / (b_C[1] - d_C[1])
    else:
        return 0

def mu_C3(x):
    if x >= c_C[2]:
        return 1
    else:
        return 1 / (1 + (a_C[2] * (c_C[2] - x)) ** b_C[2])

# =====================================================
# 4. ВВІД ДАНИХ
# =====================================================

x_A = 15
x_B = 205
x_C = 90

# =====================================================
# 5. ФАЗИФІКАЦІЯ
# =====================================================

AF_A = [
    mu_A1(x_A),
    mu_A2(x_A),
    mu_A3(x_A)
]

AF_B = [
    mu_B1(x_B),
    mu_B2(x_B),
    mu_B3(x_B)
]

AF_C = [
    mu_C1(x_C),
    mu_C2(x_C),
    mu_C3(x_C)
]

# =====================================================
# 6. ВИВЕДЕННЯ РЕЗУЛЬТАТІВ ФАЗИФІКАЦІЇ
# =====================================================

print("\n==============================")
print("РЕЗУЛЬТАТИ ФАЗИФІКАЦІЇ")
print("==============================")

print("\nМножина A:")
for i in range(3):
    print(f"{terms[i]} = {AF_A[i]:.4f}")

print("\nМножина B:")
for i in range(3):
    print(f"{terms[i]} = {AF_B[i]:.4f}")

print("\nМножина C:")
for i in range(3):
    print(f"{terms[i]} = {AF_C[i]:.4f}")

# =====================================================
# 7. БАЗА ПРАВИЛ
# =====================================================

# HIGH = індекс 2
A_high = AF_A[2]
B_high = AF_B[2]
C_high = AF_C[2]

# =====================================================
# 8. НЕЧІТКИЙ ВИСНОВОК
# =====================================================

# ---------- ПРАВИЛО 1 ----------
# IF A high AND B high AND C high
# THEN Risk = high

risk_high = min(A_high, B_high, C_high)

# ---------- ПРАВИЛО 2 ----------
# IF A high OR B high OR C high
# THEN Risk = medium

risk_medium = max(A_high, B_high, C_high)

# ---------- ПРАВИЛО 3 ----------
# IF A NOT high AND B NOT high AND C NOT high
# THEN Risk = low

risk_low = min(
    1 - A_high,
    1 - B_high,
    1 - C_high
)

# =====================================================
# 9. АГРЕГАЦІЯ
# =====================================================

print("\n==============================")
print("РЕЗУЛЬТАТИ ПРАВИЛ")
print("==============================")

print(f"Risk LOW    = {risk_low:.4f}")
print(f"Risk MEDIUM = {risk_medium:.4f}")
print(f"Risk HIGH   = {risk_high:.4f}")

# =====================================================
# 10. ДЕФАЗИФІКАЦІЯ
# =====================================================

# Центри термів
centers = {
    "low": 20,
    "medium": 50,
    "high": 80
}

# Формула центру ваги
numerator = (
    risk_low * centers["low"] +
    risk_medium * centers["medium"] +
    risk_high * centers["high"]
)

denominator = (
    risk_low +
    risk_medium +
    risk_high
)

# Захист від ділення на нуль
if denominator == 0:
    centroid = 0
else:
    centroid = numerator / denominator

# =====================================================
# 11. ФІНАЛЬНИЙ РЕЗУЛЬТАТ
# =====================================================

print("\n==============================")
print("ДЕФАЗИФІКАЦІЯ")
print("==============================")

print(f"Centroid = {centroid:.2f}")

print(f"\nСтупінь ризику = {centroid:.2f}%")